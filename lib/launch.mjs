// ============================================================
// lib/launch.mjs — 把管家拉到「用户的交互桌面会话」里跑
//
// 为什么不能就地 spawn：DSH 宿主是 nssm 服务（Session 0 / SYSTEM），
// 而 Edge 从 Session 0 起会立刻退出（exitCode 1002）。必须借
// Task Scheduler 把进程注入到登录用户的会话（Session 1）。
//
// 做法（运行时全自动，不再依赖仓库里的 .ps1 / .vbs）：
//   1. 在 <data>/tmp 下生成一个临时 .vbs（wscript 属 GUI 子系统，
//      Run 窗口样式 0 → 不弹黑框）
//   2. schtasks /create ... /ru <交互用户> /it + /run 触发
//   3. 触发后删掉这次性任务（任务删了不影响已起来的进程）
//
// macOS / Linux 没有这个问题：当前进程在哪个会话里，起出来的窗口就在哪。
// 直接 detached spawn 即可（无头服务器上跑就带 --headless）。
// ============================================================
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  TMP_DIR, HOST_SCRIPT, PORT, CDP_PORT, HEADLESS, DATA_ROOT, SESSION_USER,
  TASK_NAME, AUTOSTART_TASK, ensureDirs,
} from './config.mjs';

const isWin = process.platform === 'win32';

function log(msg) {
  const line = `[launch] ${msg}`;
  try { process.stderr.write(line + '\n'); } catch {}
}

/** VBS 字符串转义：内部双引号要写成 "" */
const vbsStr = (s) => '"' + String(s).replace(/"/g, '""') + '"';

/**
 * 清掉一小时前的临时启动器。
 * 不立刻删：vbs 是计划任务触发的入口，wscript 可能还没读到文件，
 * 删早了会让这次启动凭空失败（这种坑很难查）。
 */
function sweepTmp(maxAgeMs = 60 * 60 * 1000) {
  try {
    const now = Date.now();
    for (const f of fs.readdirSync(TMP_DIR)) {
      if (!f.endsWith('.vbs')) continue;
      const p = path.join(TMP_DIR, f);
      try {
        if (now - fs.statSync(p).mtimeMs > maxAgeMs) fs.unlinkSync(p);
      } catch {}
    }
  } catch {}
}

/** cmd 里设置环境变量的安全写法 set "K=V" */
function setEnv(env) {
  return Object.entries(env)
    .filter(([, v]) => v !== undefined && v !== null && String(v) !== '')
    .map(([k, v]) => `set "${k}=${String(v).replace(/"/g, '')}"`)
    .join('&& ');
}

/**
 * 探测「当前登录的交互用户」，给 schtasks 的 /ru 用。
 * 服务身份（SYSTEM）下 os.userInfo() 是 SYSTEM，直接拿去 /ru 会失败。
 *
 * 实测（2026-10-22，本机 SYSTEM 会话里）：
 *   · query user        —— PowerShell 里能跑，但 Node execFileSync 下去返回 1（拿不到输出）
 *   · reg query LogonUI —— 稳定可用，返回 ".\32320"
 * 所以顺序是: env → query user → 注册表 → os.userInfo()。
 */
export function interactiveUser() {
  if (SESSION_USER) return SESSION_USER;
  if (isWin) {
    // 1) query user：能拿到「哪个会话是 Active」，多用户机器上最准
    try {
      const out = execFileSync('query', ['user'], {
        encoding: 'utf8', timeout: 5000, windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'],
      });
      const rows = out.split(/\r?\n/)
        .map((l) => l.replace(/^[\s>]+/, '').trim())
        .filter((l) => /^\S+\s+\S+\s+\d+/.test(l));
      if (rows.length) {
        const active = rows.find((r) => /\bActive\b/i.test(r)) || rows[0];
        const user = active.split(/\s+/)[0];
        if (user && !/^(SYSTEM|NETWORK|LOCAL)$/i.test(user)) return user;
      }
    } catch { /* 落到注册表 */ }

    // 2) 注册表：最后一次登录的用户（服务身份下也能读）
    for (const key of ['LastLoggedOnSAMUser', 'LastLoggedOnUser']) {
      try {
        const out = execFileSync('reg', [
          'query',
          'HKLM\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Authentication\\LogonUI',
          '/v', key,
        ], { encoding: 'utf8', timeout: 5000, windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'] });
        const m = out.match(/REG_SZ\s+(\S+)/);
        if (m) {
          const user = m[1].split('\\').pop();   // ".\32320" / "HOST\32320" → "32320"
          if (user && !/^(SYSTEM|NETWORK|LOCAL)$/i.test(user)) return user;
        }
      } catch { /* 下一个 */ }
    }
  }
  try {
    const u = os.userInfo().username;
    if (u && !/^(SYSTEM|NETWORK SERVICE|LOCAL SERVICE)$/i.test(u)) return u;
  } catch {}
  return '';
}

/** 生成启动器 vbs，返回路径 */
function writeVbs({ headless, port, extras = {} }) {
  ensureDirs();
  sweepTmp();
  const node = process.execPath;
  const env = {
    STAR_BROWSER_HEADLESS: headless ? '1' : '0',
    STAR_HOST_PORT: String(port),
    STAR_BROWSER_CDP_PORT: String(CDP_PORT),
    STAR_BROWSER_DATA: DATA_ROOT,
    ...extras,
  };
  const cmdLine = `cmd /c ${setEnv(env)}&& "${node}" "${HOST_SCRIPT}"`;
  const body = [
    "' auto-generated by star-browser (safe to delete)",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.Run ${vbsStr(cmdLine)}, 0, False`,
    '',
  ].join('\r\n');
  const file = path.join(TMP_DIR, `launch-${Date.now()}.vbs`);
  fs.writeFileSync(file, body, 'utf8');
  return file;
}

function schtasks(args) {
  return execFileSync('schtasks', args, {
    encoding: 'utf8', timeout: 20000, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'],
  });
}

/**
 * 在交互桌面会话里起一个管家。
 * @returns {{mode:'schtasks'|'spawn', task?:string, vbs?:string, pid?:number, user?:string}}
 */
export function launchOnDesktop({ headless = HEADLESS, port = PORT, task = TASK_NAME, keepTask = false, extraEnv = {} } = {}) {
  if (!isWin) {
    // 非 Windows：就地 detached 起（要求当前进程本身在桌面/图形会话里）
    const child = spawn(process.execPath, [HOST_SCRIPT], {
      detached: true,
      stdio: 'ignore',
      env: { ...process.env, STAR_BROWSER_HEADLESS: headless ? '1' : '0', STAR_HOST_PORT: String(port) },
    });
    child.unref();
    return { mode: 'spawn', pid: child.pid };
  }

  const user = interactiveUser();
  if (!user) {
    throw new Error(
      '探测不到当前登录的交互用户，没法把浏览器塞进桌面会话。\n' +
      '请设置环境变量 STAR_BROWSER_SESSION_USER=<用户名> 再试，或手动双击启动。'
    );
  }
  const vbs = writeVbs({ headless, port, extras: extraEnv });
  const tr = `wscript.exe "${vbs}"`;
  const args = ['/create', '/tn', task, '/tr', tr, '/sc', 'once', '/st', '00:00', '/ru', user, '/it', '/f'];
  try {
    schtasks(args);
  } catch (e) {
    // 有些环境 /it 需要交互权限；退一步不带 /it 再试
    try {
      schtasks(['/create', '/tn', task, '/tr', tr, '/sc', 'once', '/st', '00:00', '/ru', user, '/f']);
    } catch (e2) {
      throw new Error('创建计划任务失败：' + (e2.stderr || e2.message || String(e2)));
    }
  }
  schtasks(['/run', '/tn', task]);
  if (!keepTask) {
    // 触发后删任务：删掉不会杀掉已经跑起来的进程
    setTimeout(() => {
      try { schtasks(['/delete', '/tn', task, '/f']); } catch {}
    }, 5000).unref?.();
  }
  log(`launched in user session "${user}" via task ${task}`);
  return { mode: 'schtasks', task, vbs, user };
}

/** 注册「登录即静默启动」（真正的安装即用） */
export function installAutostart({ headless = HEADLESS, port = PORT } = {}) {
  if (!isWin) {
    return {
      ok: false,
      hint: 'macOS/Linux 请自己加到登录项（launchd / systemd --user），例如：\n' +
        `  node ${HOST_SCRIPT}  →  用 PM2/systemd 守护`,
    };
  }
  const user = interactiveUser();
  if (!user) return { ok: false, hint: '探测不到登录用户，请设 STAR_BROWSER_SESSION_USER' };
  const vbs = writeVbs({ headless, port, extras: { STAR_BROWSER_AUTOSTART: '1' } });
  try {
    schtasks(['/create', '/tn', AUTOSTART_TASK, '/tr', `wscript.exe "${vbs}"`, '/sc', 'onlogon', '/ru', user, '/it', '/f']);
    return { ok: true, task: AUTOSTART_TASK, user, vbs };
  } catch (e) {
    return {
      ok: false,
      error: (e.stderr || e.message || String(e)).trim(),
      hint: '注册登录自启通常需要管理员权限。用管理员开的终端再跑一次 `star-browser --install-task`。',
    };
  }
}

export function removeAutostart() {
  if (!isWin) return { ok: false, hint: '非 Windows 无需处理' };
  try {
    schtasks(['/delete', '/tn', AUTOSTART_TASK, '/f']);
    return { ok: true };
  } catch (e) {
    return { ok: false, error: (e.stderr || e.message || String(e)).trim() };
  }
}
